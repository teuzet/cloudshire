export function formatWorldContractForPrompt(config = {}) {
  const world = String(config?.canon?.world || '').trim();
  const patron = String(config?.canon?.patron || '').trim();
  const lines = [
    'WORLD CONTRACT (чеклист, совпадает с canon.world / canon.patron):',
    ...WORLD_CONTRACT_ITEMS.map((item) => `- ${item.text}`),
  ];
  if (world) {
    lines.push('', 'Фрагмент canon.world:', world.slice(0, 2400));
  }
  if (patron) {
    lines.push('', 'Фрагмент canon.patron:', patron.slice(0, 1200));
  }
  return lines.join('\n');
}

export function matchCosmologyHeuristic(text) {
  const raw = String(text || '').trim();
  if (!raw) return [];
  const hits = [];
  for (const h of COSMOLOGY_HEURISTICS) {
    const m = raw.match(h.re);
    if (!m) continue;
    hits.push({
      id: h.id,
      requested: m[0],
      reason: h.reason,
      adaptations: [...h.adaptations],
    });
  }
  return hits;
}

export function worldContractCoversCanonBans(config = {}) {
  const blob = `${config?.canon?.world || ''}\n${config?.canon?.patron || ''}`.toLowerCase();
  return {
    humans: /люд|человек/.test(blob),
    noFlight: /не летают|воздушн/.test(blob),
    conjunction: /сопряжен/.test(blob),
    lowMagic: /low-magic|магия/.test(blob),
    onePatron: /покровител/.test(blob),
    noCosmos: /космос/.test(blob),
  };
}

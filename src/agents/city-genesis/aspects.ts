export function aspectBatches(): AspectDef[][] {
  const out: AspectDef[][] = [];
  for (let i = 0; i < ASPECTS.length; i += ASPECT_BATCH) out.push(ASPECTS.slice(i, i + ASPECT_BATCH));
  return out;
}

/** Описание города: разделы по порядку, с заголовками. */
export function assembleDescription(aspects: Record<string, string>): string {
  return ASPECTS.filter((a) => aspects[a.id]?.trim())
    .map((a) => `## ${a.title}\n\n${aspects[a.id]!.trim()}`)
    .join('\n\n');
}
